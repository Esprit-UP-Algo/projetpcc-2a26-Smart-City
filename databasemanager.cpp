bool DatabaseManager::addTransaction(const QVariantMap &data)
{
    QSqlDatabase db = database();
    QSqlQuery q(db);

    q.prepare(R"(
        INSERT INTO transactions (code_unique, type, montant, date_transaction, categorie, description)
        VALUES (:code, :type, :montant, TO_DATE(:date_transaction, 'YYYY-MM-DD'), :categorie, :description)
    )");

    q.bindValue(":code", data.value("code"));
    q.bindValue(":type", data.value("type"));
    q.bindValue(":montant", data.value("montant"));
    q.bindValue(":date_transaction", data.value("date"));  // on garde le format yyyy-MM-dd
    q.bindValue(":categorie", data.value("categorie"));
    q.bindValue(":description", data.value("description"));

    if (!q.exec()) {
        QMessageBox::critical(nullptr, "Erreur SQL",
                              "Échec de l'insertion dans Oracle :\n" + q.lastError().text());
        qWarning() << "[DatabaseManager] ❌ Erreur ajout transaction:" << q.lastError().text();
        return false;
    }

    db.commit();
    qDebug() << "[DatabaseManager] ✅ Transaction ajoutée:" << data.value("code").toString();
    return true;
}

bool DatabaseManager::updateTransaction(const QString &code, const QVariantMap &data)
{
    QSqlDatabase db = database();
    QSqlQuery q(db);

    q.prepare(R"(
        UPDATE transactions
        SET type = :type,
            montant = :montant,
            date_transaction = TO_DATE(:date_transaction, 'YYYY-MM-DD'),
            categorie = :categorie,
            description = :description
        WHERE code_unique = :code
    )");

    q.bindValue(":code", code);
    q.bindValue(":type", data.value("type"));
    q.bindValue(":montant", data.value("montant"));
    q.bindValue(":date_transaction", data.value("date"));
    q.bindValue(":categorie", data.value("categorie"));
    q.bindValue(":description", data.value("description"));

    if (!q.exec()) {
        QMessageBox::critical(nullptr, "Erreur SQL",
                              "Échec de la mise à jour :\n" + q.lastError().text());
        qWarning() << "[DatabaseManager] ❌ Erreur update transaction:" << q.lastError().text();
        return false;
    }

    db.commit();
    qDebug() << "[DatabaseManager] ✅ Transaction mise à jour:" << code;
    return true;
}

