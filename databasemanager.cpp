DatabaseManager::DatabaseManager(QObject *parent)
    : QObject(parent)
{
    qDebug() << "[DatabaseManager] Constructeur appelé";

    QSqlDatabase db = Connection::getInstance().getDatabase();
    if (!db.isValid() || !db.isOpen()) {
        qWarning() << "[DatabaseManager] Connexion invalide ou fermée !";
    } else {
        qDebug() << "[DatabaseManager] Connexion Oracle active.";
    }

    ensureSchema();
}

QSqlDatabase DatabaseManager::database() const
{
    return Connection::getInstance().getDatabase();
}

void DatabaseManager::ensureSchema()
{
    QSqlQuery q(database());

    // Table Residents
    if (!q.exec("CREATE TABLE residents ("
                "cin VARCHAR2(20) PRIMARY KEY, "
                "nom VARCHAR2(50), "
                "prenom VARCHAR2(50), "
                "adresse VARCHAR2(100), "
                "telephone VARCHAR2(20), "
                "email VARCHAR2(100), "
                "date_entree DATE)")) {
        if (!q.lastError().text().contains("name is already used", Qt::CaseInsensitive))
            qWarning() << "[DatabaseManager] Erreur création table residents:" << q.lastError().text();
    }

    // Table Transactions
    if (!q.exec("CREATE TABLE transactions ("
                "code VARCHAR2(20) PRIMARY KEY, "
                "type VARCHAR2(50), "
                "montant NUMBER(10,2), "
                "date_transaction DATE, "
                "description VARCHAR2(200))")) {
        if (!q.lastError().text().contains("name is already used", Qt::CaseInsensitive))
            qWarning() << "[DatabaseManager] Erreur création table transactions:" << q.lastError().text();
    }

    // Table Incidents
    if (!q.exec("CREATE TABLE incidents ("
                "id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                "type VARCHAR2(50), "
                "description VARCHAR2(200), "
                "date_incident DATE, "
                "statut VARCHAR2(50))")) {
        if (!q.lastError().text().contains("name is already used", Qt::CaseInsensitive))
            qWarning() << "[DatabaseManager] Erreur création table incidents:" << q.lastError().text();
    }

    // Table Véhicules
    if (!q.exec("CREATE TABLE vehicules ("
                "id VARCHAR2(20) PRIMARY KEY, "
                "type VARCHAR2(50), "
                "capacite NUMBER, "
                "zone VARCHAR2(100), "
                "horaire VARCHAR2(50), "
                "statut VARCHAR2(50), "
                "date_ajout DATE, "
                "temps_utilise NUMBER(10,1))")) {
        if (!q.lastError().text().contains("name is already used", Qt::CaseInsensitive))
            qWarning() << "[DatabaseManager] Erreur création table vehicules:" << q.lastError().text();
    }

    qDebug() << "[DatabaseManager] Schéma vérifié ou déjà existant.";
}

