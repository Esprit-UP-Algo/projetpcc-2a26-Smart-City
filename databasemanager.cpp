bool DatabaseManager::addVehicule(const QVariantMap &data)
{
    QSqlQuery q(database());
    q.prepare("INSERT INTO vehicules (id, type, capacite, zone, horaire, statut, date_ajout, temps_utilise) "
              "VALUES (:id, :type, :capacite, :zone, :horaire, :statut, :date_ajout, :temps_utilise)");

    q.bindValue(":id", data["id"]);
    q.bindValue(":type", data["type"]);
    q.bindValue(":capacite", data["capacite"]);
    q.bindValue(":zone", data["zone"]);
    q.bindValue(":horaire", data["horaire"]);
    q.bindValue(":statut", data["statut"]);

    QString dateAjout = data["date_ajout"].toString();
    if (dateAjout.isEmpty())
        dateAjout = QDateTime::currentDateTime().toString("yyyy-MM-dd hh:mm:ss");

    q.bindValue(":date_ajout", dateAjout);
    q.bindValue(":temps_utilise", data["temps_utilise"]);

    if(!q.exec())
    {
        qDebug() << "Erreur SQL:" << q.lastError().text();
        return false;
    }
    return true;
}


